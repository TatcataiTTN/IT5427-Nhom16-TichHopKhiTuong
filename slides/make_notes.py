#!/usr/bin/env python3
# Builds notes.tex from the talk script (argv[1], default ../talk.md): for each slide header `## 1.2.` (main part,
# phần.mục) or `## 32.` (phụ lục, so trang), its "Lời nói" and "Chuyển ý" become \slidenote{1.2} / \slidenote{32},
# so the speaker notes stay in one place (the script).
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else HERE.parent / "talk.md"

SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def tex(s):
    out = []
    for i, part in enumerate(re.split(r"`([^`]*)`", s)):
        esc = "".join(SPECIAL.get(c, c) for c in part)
        out.append(r"\texttt{%s}" % esc if i % 2 else esc)
    s = "".join(out)
    s = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", s)
    return s.replace("…", r"\ldots{}").replace('"', "''")


def main():
    text = SRC.read_text(encoding="utf-8")
    notes = {}
    for m in re.finditer(r"^## (\d+(?:\.\d+)?)\. .*?$(.*?)(?=^## |^# |\Z)", text, re.S | re.M):
        code, body = m.group(1), m.group(2)
        parts = []
        for label in ("Lời nói", "Lời nói (dẫn)", "Chuyển ý"):
            b = re.search(r"^\*\*%s\*\*\n((?:>.*\n?)+)" % re.escape(label), body, re.M)
            if not b:
                continue
            paras = [p.strip() for p in re.sub(r"^> ?", "", b.group(1), flags=re.M).split("\n\n")]
            paras = [tex(" ".join(p.split("\n"))) for p in paras if p]
            head = r"\textbf{Chuyển ý:} " if label == "Chuyển ý" else ""
            parts.append(head + "\n\n".join(paras))
        notes[code] = "\n\n".join(parts)
    lines = ["%% Generated by make_notes.py from %s; do not edit." % SRC.name]
    for code, body in notes.items():
        lines.append(r"\expandafter\def\csname slidenote@%s\endcsname{%s}" % (code, body))
    (HERE / "notes.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("notes for %d slides" % len(notes), file=sys.stderr)


if __name__ == "__main__":
    main()
